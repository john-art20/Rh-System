    private void btnEntrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEntrarActionPerformed
      funcionarios func = new funcionarios();
        
      func.setId(txtLogin.getText());
       func.setSenha(txtSenha.getText());
        
      
        funcionarios funcionario = funcionarios.autenticarUsuario(func);
        
        if (funcionario != null) {
                                  
         if( funcionario.getTipoPerfil().equalsIgnoreCase("CLT") ) {
         JOptionPane.showMessageDialog(null, "Bem-vindo, CLT " + funcionario.getNome() + "");
                                       
                                     
                      CLT clt = new CLT( funcionario);
                     clt.setVisible(true);                
                                       
                                       
         } else if ( funcionario.getTipoPerfil().equalsIgnoreCase("PJ") ) {
      JOptionPane.showMessageDialog(null, "Bem-vindo, PJ " + funcionario.getNome() + "");
                    
                    PJ pj = new PJ(funcionario);
                    pj.setVisible(true);
                                        
                                        
                                    
        } else if ( funcionario.getTipoPerfil().equalsIgnoreCase("SP") ) {
        JOptionPane.showMessageDialog(null, "Bem-vindo, SP " + funcionario.getNome() + "");
        
        SP sp = new SP(funcionario);
                    sp.setVisible(true);
        
        
         } else if ( funcionario.getTipoPerfil().equalsIgnoreCase("RH") ) {
        JOptionPane.showMessageDialog(null, "Bem-vindo, RH " + funcionario.getNome() + "");
                                      
                   RH rh = new RH(funcionario);
                    rh.setVisible(true);                  
                                  } 
            } else {
        JOptionPane.showMessageDialog(null, "Erro de autenticação! Verifique se os dados estão corretos.");
                              }
        dispose();
        
    }//GEN-LAST:event_btnEntrarActionPerformed

