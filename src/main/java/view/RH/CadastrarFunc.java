    private void btnCadActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCadActionPerformed
       if (this.func == null) {
        this.func = new funcionarios();
       }
       String textoValorHora = txtValor.getText().trim();
        textoValorHora = textoValorHora.replace(",", ".");
       
       this.func.setId(txtId.getText());
    this.func.setNome(txtNome.getText());
    this.func.setSenha(txtSenha.getText());
    this.func.setTipoPerfil(txtModel.getText());
    this.func.setValorHora(Double.parseDouble(textoValorHora));
    
    funcionarios.Cadastrar(this.func);
       JOptionPane.showMessageDialog(null, "Funcionário cadastrado com sucesso!");   
       
       txtId.setText("");
    txtNome.setText("");
    txtSenha.setText("");
    txtModel.setText("");
    txtValor.setText("");
  txtId.requestFocus();
    
    }//GEN-LAST:event_btnCadActionPerformed

