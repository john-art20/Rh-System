    private void btnCadActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCadActionPerformed
  try {
    // 1. Pega os textos dos campos
    String inicio = txtInicio.getText();
    String termino = txtTermino.getText();
    String CRM = txtCRM.getText();
    String medico = txtMedico.getText();
    
    if (this.func == null) {
        this.func = new funcionarios();
    }
    this.func.setId(txtId.getText());
    this.func.setNome(txtNome.getText());
    
    // 2. Converte as datas
    DateTimeFormatter formato = DateTimeFormatter.ofPattern("yyyy-MM-dd");
    LocalDate dataInicioLocal = LocalDate.parse(inicio, formato);
    LocalDate dataTerminoLocal = LocalDate.parse(termino, formato);
    
    java.sql.Date inicioSql = java.sql.Date.valueOf(dataInicioLocal);
    java.sql.Date terminoSql = java.sql.Date.valueOf(dataTerminoLocal);
    
    // 3. Chamada limpa (NomeDaClasse.nomeDoMetodo)
    Atestado.CadAtestado(inicioSql, terminoSql, CRM, medico, this.func);
    
    
    JOptionPane.showMessageDialog(this, "Atestado registado com sucesso!");
    
    txtId.setText("");
    txtNome.setText("");
    txtInicio.setText("");
    txtTermino.setText("");
    txtCRM.setText("");
    txtMedico.setText("");
    txtId.requestFocus();
    
} catch (DateTimeParseException e) {
    JOptionPane.showMessageDialog(this, "Data inválida! Use o formato yyyy-MM-dd.");
}
    }//GEN-LAST:event_btnCadActionPerformed

