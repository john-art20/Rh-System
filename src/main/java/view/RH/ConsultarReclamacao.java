    private void btnConsultaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConsultaActionPerformed
        // TODO add your handling code here:
        
          String idReclamacao = txtIDC.getText();
    String idSupervisor = txtIDS.getText();
    
    // Chama o método passando o ID (que pode estar preenchido ou vazio)
    String resultado = RelatorioServico.consultaR(idSupervisor, idReclamacao);
    
    if (resultado != null) {
        // Joga todas as descrições encontradas para dentro do JTextArea
        tatext.setText(resultado);
    } else {
        tatext.setText("");
        JOptionPane.showMessageDialog(this, "Nenhuma reclamação encontrada.");
    }
    }//GEN-LAST:event_btnConsultaActionPerformed

