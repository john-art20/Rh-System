    private void btnPesquisarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPesquisarActionPerformed
        funcionarios func = new funcionarios();
        func.setId(txtPesquisar.getText()); // O campo de texto onde digita o ID

        DefaultTableModel modelo = (DefaultTableModel) Pontos.getModel();
        modelo.setRowCount(0); // Limpa a tabela antes de carregar novos dados

        // Chama o método que agora retorna uma lista de registros
        List<String[]> pontos = horasPJ.consultarPontoPJ(func);

        for (String[] linha : pontos) {
            modelo.addRow(linha); // Adiciona cada linha na tabela visual
        }
    }//GEN-LAST:event_btnPesquisarActionPerformed

