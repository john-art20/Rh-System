    private void preencher(horasPJ folha) {
        if (folha == null) return;

        Func.setText(folha.getNome());
        ID.setText(folha.getId());
        
        Dias.setText(String.valueOf(folha.getTotalDias()));
        Valor.setText(String.format("R$ %.2f", folha.getValorHora()));
        Horas.setText(folha.getHorasExatas() + "h " + folha.getMinutosRestantes() + "min");
        Extra.setText(String.format("%.2f h", folha.getHorasExtras()));
        ValorExtra.setText(String.format("R$ %.2f", folha.getValorExtras()));
        Bruto.setText(String.format("R$ %.2f", folha.getTotalBruto()));
       
        Limpo.setText(String.format("R$ %.2f", folha.getTotalLimpo()));
    }

