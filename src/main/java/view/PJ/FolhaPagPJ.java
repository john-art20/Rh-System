    private void btnVisualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnVisualizarActionPerformed

        horasPJ folha = horasPJ.calcularFolhaPJ(func);

        if (folha != null) {
            FolhaPagPJ tela = new FolhaPagPJ(folha);
            tela.setVisible(true);
            dispose();
        } else {
            JOptionPane.showMessageDialog(this, "Nenhum registro de ponto encontrado para este funcionário.");
        }

    }//GEN-LAST:event_btnVisualizarActionPerformed

