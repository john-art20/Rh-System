    private void btnCadActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCadActionPerformed
           try {
   
    String identify= txtIdentify.getText();
    String textoData = txtData.getText();
    String texto= tabom.getText();
    
    // 2. Define o formato em que o usuário digitou a data
    DateTimeFormatter formato = DateTimeFormatter.ofPattern("yyyy-MM-dd");
    
    // 3. Converte a String para LocalDate
    LocalDate dataLocal = LocalDate.parse(textoData, formato);
    
    // 4. Converte o LocalDate para java.sql.Date (para enviar ao banco)
    java.sql.Date dataSql = java.sql.Date.valueOf(dataLocal);
    
    RelatorioServico.Description( identify,dataSql,this.func,texto );
     JOptionPane.showMessageDialog(this, "Reclamação registrada com sucesso!");
     txtIdentify.setText("");
     txtData.setText("");
     tabom.setText("");
      txtIdentify.requestFocus();
    
} catch (DateTimeParseException e) {
    JOptionPane.showMessageDialog(this, "Data inválida! Certifique-se de usar o formato yyyy-MM-dd.");
}
    }//GEN-LAST:event_btnCadActionPerformed

